    /**
     * Знайти область по назві (часткове співпадіння)
     */
    public static double[][][] findOblast(String alertLocationTitle) {
        if (alertLocationTitle == null) return null;
        String lower = alertLocationTitle.toLowerCase();
        for (Map.Entry<String, double[][][]> entry : BOUNDARIES.entrySet()) {
            String key = entry.getKey().toLowerCase();
            // Порівнюємо по ключовому слову (область, місто)
            String[] keyWords = key.split(" ");
            for (String word : keyWords) {
                if (word.length() > 4 && lower.contains(word)) {
                    return entry.getValue();
                }
            }
        }
        return null;
    }

    /**
     * Центроїд першого полігону (для іконки літака)
     */
    public static double[] getCentroid(double[][][] polygons) {
        if (polygons == null || polygons.length == 0) return null;
        double[] ring = new double[0];
        double sumLon = 0, sumLat = 0;
        double[][] pts = polygons[0];
        for (double[] pt : pts) {
            sumLon += pt[0];
            sumLat += pt[1];
        }
        return new double[]{sumLon / pts.length, sumLat / pts.length};
    }
